#!/usr/bin/env python3
"""
gen_talents.py -- builds TopFit's talentdata.lua (the talent order the WoWSims sim reads) from the sim clone.

usage (from the TopFit folder):  python tools/gen_talents.py [--repo ../Forever] [--addon .]
  (tools/update_data.py runs this together with the other generators.)  Writes <addon>/talentdata.lua.

The sim reads a character's talents as a positional string: digit i of tree t is talent i of tree t in
ui/sim/talents/trees/<class>.json. The game client exposes talents through C_Traits instead, so for every class
this lists each tree's talents by TraitDefinition ID, in the sim's order. simc_export.lua then looks up the rank of
each definition ID and writes the digits in that order. (The official WoWSims exporter addon works the same way.)
Run it again whenever the sim's talent trees change.
"""
import argparse
import json
from pathlib import Path

from fvspells import add_common_args, attribution_lines, require_repo

CLASSES = ["druid", "hunter", "mage", "paladin", "priest", "rogue", "shaman", "warlock", "warrior"]


def generate(repo, out_path):
    repo = require_repo(repo, "trees")
    trees_dir = repo / "ui/sim/talents/trees"
    lines = [
        "-- talentdata.lua -- GENERATED by gen_talents.py from the WoW: Forever sim data. DO NOT EDIT BY HAND.",
        *attribution_lines(repo),
        "-- TopFit.TalentTrees[CLASS] = { tree1, tree2, tree3 }; each tree lists TraitDefinition IDs in the sim's order.",
        "TopFit.TalentTrees = {",
    ]
    total = 0
    for cls in CLASSES:
        trees = json.loads((trees_dir / ("%s.json" % cls)).read_text(encoding="utf-8"))
        if len(trees) != 3:
            raise SystemExit("%s.json has %d trees, expected 3" % (cls, len(trees)))
        seen = {}
        for ti, tree in enumerate(trees, 1):
            for t in tree["talents"]:
                if int(t["definitionId"]) in seen:
                    print("warning: %s definition %s is in tree %d and tree %d; ranks would count in both"
                          % (cls, t["definitionId"], seen[int(t["definitionId"])], ti))
                seen[int(t["definitionId"])] = ti
        lines.append("\t%s = {" % cls.upper())
        for tree in trees:
            ids = [str(int(t["definitionId"])) for t in tree["talents"]]
            total += len(ids)
            lines.append("\t\t{ %s }, -- %s" % (", ".join(ids), tree["name"]))
        lines.append("\t},")
    lines.append("}")
    out_path = Path(out_path)
    new = "\n".join(lines) + "\n"
    changed = not out_path.exists() or out_path.read_text(encoding="utf-8").replace("\r\n", "\n") != new
    if changed:
        out_path.write_text(new, encoding="utf-8", newline="\n")
    print("%d talents across %d classes (%s)" % (total, len(CLASSES), "changed" if changed else "unchanged"))
    print("wrote" if changed else "kept", out_path)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate talentdata.lua from the Forever sim clone.")
    add_common_args(parser)
    args = parser.parse_args(argv)
    generate(args.repo, args.addon / "talentdata.lua")


if __name__ == "__main__":
    main()
